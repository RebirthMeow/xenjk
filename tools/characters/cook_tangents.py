"""cook_tangents.py: the renderer's prepared tangents (cache/tangents/<key>.xtan) built ahead of play.

    python tools/characters/cook_tangents.py --out DIR [--base GameData/base] [--all] [--compare DIR ...] [--pack OUT.pk3]

A first-ever load of a hero spends 0.4-0.7 s in MikkTSpace (codemp/rd-vulkan/vk_tangent_cache.cpp); the game writes
the result to cache/tangents and reads it on later loads, from the homepath or a pk3. This tool computes those files
for every installed player GLM (--all: every GLM) without the game: it extracts the key, the computation and the file
layout from the renderer's own sources (vk_tangent_cache.cpp, vk_mikktspace.cpp, utils/mikktspace), compiles them
with MSVC for x86 with the renderer's float flags (/O2 /arch:SSE2, precise), and runs that on each GLM as the game
resolves it (a later pack name wins).

--out DIR writes DIR/cache/tangents/<key>.xtan; --pack OUT.pk3 stores them in a pack (never rebuilt in place).
--compare DIR checks the cooked tangents against .xtan files the game wrote (any version: matched by GLM size and
vertex counts, the tangent bytes compared), so the extraction and the compiler are tested against the game itself. The cooker is a 32-bit build; compare it
against files the installed client wrote (the 64-bit one) before shipping cooked files for it.
Runs at idle priority. Writes nothing under --base.
"""
import argparse
import ctypes
import os
import re
import shutil
import struct
import subprocess
import sys
import tempfile
import time
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RD = ROOT / 'codemp' / 'rd-vulkan'


def find_vcvars():
    """vcvars32.bat of the newest Visual Studio with the C++ tools, as vswhere reports it"""
    vswhere = Path(os.environ.get('ProgramFiles(x86)', r'C:\Program Files (x86)')) / 'Microsoft Visual Studio' / \
        'Installer' / 'vswhere.exe'
    if not vswhere.is_file():
        return None
    r = subprocess.run([str(vswhere), '-latest', '-products', '*', '-requires',
                        'Microsoft.VisualStudio.Component.VC.Tools.x86.x64', '-property', 'installationPath'],
                       capture_output=True, text=True)
    path = r.stdout.strip().splitlines()[0] if r.stdout.strip() else ''
    vc = Path(path) / 'VC' / 'Auxiliary' / 'Build' / 'vcvars32.bat' if path else None
    return vc if vc and vc.is_file() else None


def lower_priority():
    if os.name == 'nt':
        k = ctypes.windll.kernel32
        k.SetPriorityClass(k.GetCurrentProcess(), 0x40)     # IDLE_PRIORITY_CLASS: children inherit it


def default_base():
    if (ROOT / 'game_directory').is_dir():
        root = ROOT
    else:
        common = subprocess.run(['git', '-C', str(ROOT), 'rev-parse', '--git-common-dir'], capture_output=True, text=True).stdout.strip()
        root = (ROOT / common).resolve().parent if common else ROOT
    return root / 'game_directory' / 'Jedi Academy' / 'GameData' / 'base'


def function(src, signature):
    """the definition starting with signature, through its closing brace at column 0"""
    a = src.index(signature)
    b = src.index('\n}\n', a) + 3
    return src[a:b]


def block(src, start, end):
    a = src.index(start)
    return src[a:src.index(end, a)]


def generate(build):
    tan = (RD / 'vk_tangent_cache.cpp').read_text(encoding='utf-8').replace('\r\n', '\n')
    mik = (RD / 'vk_mikktspace.cpp').read_text(encoding='utf-8').replace('\r\n', '\n')
    parts = [
        block(tan, '#define XTAN_MAGIC', 'struct tangentEntry_t'),
        function(mik, 'int R_FixMikktVertIndex('),
        function(mik, 'int mikkt_bsp_face_GetNumVerticesOfFace('),
        block(mik, 'struct GlmMeshData', '//\n// MDV'),
        function(tan, 'static uint64_t R_TangentMix('),
        function(tan, 'static const mdxmSurface_t *R_TangentFirstSurface('),
        function(tan, 'static void R_TangentCounts('),
        function(tan, 'void R_TangentComputeLods('),
        function(tan, 'uint64_t R_TangentKeyOf('),
        function(tan, 'void R_TangentSerialize('),
    ]
    prelude = r'''// generated by tools/characters/cook_tangents.py from the renderer's sources: do not edit
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <stdint.h>
#include <vector>
#include "qcommon/q_shared.h"
#define MDXABONEDEF
#include "rd-common/mdx_format.h"
extern "C" {
#include "rd-vulkan/utils/mikktspace/mikktspace.h"
}
typedef unsigned int glIndex_t;
#ifndef Com_Memcpy
#define Com_Memcpy memcpy
#endif
'''
    main = r'''
// cook <glm> <outdir>: prints "key glmSize lods vertices"
int main( int argc, char **argv ) {
	if ( argc < 3 ) return 2;
	FILE *f = fopen( argv[1], "rb" );
	if ( !f ) return 3;
	fseek( f, 0, SEEK_END );
	const long len = ftell( f );
	fseek( f, 0, SEEK_SET );
	std::vector<byte> buf( len > 0 ? len : 1 );
	if ( len <= 0 || fread( &buf[0], 1, len, f ) != (size_t)len ) return 4;
	fclose( f );
	const mdxmHeader_t *mdxm = (const mdxmHeader_t *)&buf[0];
	if ( len < (long)sizeof( mdxmHeader_t ) || mdxm->ident != MDXM_IDENT || mdxm->version != MDXM_VERSION
		|| mdxm->ofsEnd <= 0 || mdxm->ofsEnd > len || mdxm->numLODs < 1 ) {
		printf( "bad\n" );
		return 5;
	}
	std::vector<std::vector<float> > lods;
	std::vector<int> counts;
	R_TangentComputeLods( mdxm, lods );
	R_TangentCounts( mdxm, counts );
	const uint64_t key = R_TangentKeyOf( mdxm );
	std::vector<byte> out;
	R_TangentSerialize( key, (uint32_t)mdxm->ofsEnd, counts, lods, out );
	char path[1200];
	snprintf( path, sizeof( path ), "%s/%08x%08x.xtan", argv[2], (unsigned)( key >> 32 ), (unsigned)key );
	FILE *o = fopen( path, "wb" );
	if ( !o || fwrite( &out[0], 1, out.size(), o ) != out.size() ) return 6;
	fclose( o );
	int verts = 0;
	for ( size_t l = 0; l < counts.size(); l++ ) verts += counts[l];
	printf( "%08x%08x %d %d %d\n", (unsigned)( key >> 32 ), (unsigned)key, mdxm->ofsEnd, mdxm->numLODs, verts );
	return 0;
}
'''
    src = prelude + '\n'.join(parts) + main
    (build / 'cook.cpp').write_text(src, encoding='utf-8')
    vc = find_vcvars()
    if not vc:
        sys.exit('no Visual Studio with the C++ tools (vswhere found no vcvars32.bat): the cooker must be built with '
                 'the renderer\'s compiler')
    inc = '/I"%s" /I"%s"' % (ROOT / 'codemp', ROOT / 'shared')
    flags = '/nologo /O2 /arch:SSE2 /EHsc /MD /DNDEBUG /DFINAL_BUILD /D_CRT_SECURE_NO_WARNINGS /DNOMINMAX /W0'
    bat = build / 'build.bat'
    bat.write_text('@echo off\r\ncall "%s" >nul\r\ncd /d "%s"\r\ncl %s %s /Tc"%s" /c /Fo"mikktspace.obj" || exit /b 1\r\n'
                   'cl %s %s cook.cpp mikktspace.obj /Fe"cook.exe" || exit /b 1\r\n' % (
                       vc, build, flags, inc, RD / 'utils' / 'mikktspace' / 'mikktspace.c', flags, inc), encoding='utf-8')
    r = subprocess.run(['cmd', '/c', str(bat)], capture_output=True, text=True)
    if r.returncode or not (build / 'cook.exe').is_file():
        print(r.stdout[-3000:], r.stderr[-2000:])
        sys.exit('cooker build failed')
    return build / 'cook.exe'


def installed_glms(base, every):
    """{qpath: (pack, member)} as the game resolves them (a later pack in the engine's order wins). Loose
    files are not looked at (in the packs' own folder the engine searches the packs before loose files)"""
    sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    from pack_order import pack_sort_key
    found = {}
    for p in sorted(base.glob('*.pk3'), key=pack_sort_key):
        try:
            z = zipfile.ZipFile(p)
        except zipfile.BadZipFile:
            continue
        for n in z.namelist():
            low = n.lower().replace('\\', '/')
            if not low.endswith('.glm'):
                continue
            if not every and not (low.startswith('models/players/') and low.endswith('/model.glm')):
                continue
            found[low] = (p, n)
    return found


def xtan_index(dirs):
    """(glmSize, counts) -> tangent bytes, for files the game wrote"""
    idx = {}
    for d in dirs:
        for f in Path(d).rglob('*.xtan'):
            b = f.read_bytes()
            if len(b) < 24:
                continue
            magic, ver, key, size, nl = struct.unpack_from('<IIQII', b)
            counts = struct.unpack_from('<%dI' % nl, b, 24)
            idx.setdefault((size, counts), (b[24 + 4 * nl:], f, ver))
    return idx


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--base', type=Path)
    ap.add_argument('--out', type=Path, required=True)
    ap.add_argument('--all', action='store_true', help='every GLM, not only models/players/*/model.glm')
    ap.add_argument('--compare', type=Path, nargs='*', default=[])
    ap.add_argument('--pack', type=Path)
    ap.add_argument('--limit', type=int, default=0)
    a = ap.parse_args()
    lower_priority()
    base = a.base or default_base()
    tandir = a.out / 'cache' / 'tangents'
    tandir.mkdir(parents=True, exist_ok=True)
    build = Path(tempfile.mkdtemp(prefix='cook_tangents_'))
    try:
        cook(a, base, tandir, build)
    finally:
        shutil.rmtree(build, ignore_errors=True)   # the cooker, its objects and the last GLM: rebuilt each run


def cook(a, base, tandir, build):
    exe = generate(build)
    glms = installed_glms(base, a.all)
    ref = xtan_index(a.compare) if a.compare else {}
    print('%d GLMs; %d reference files' % (len(glms), len(ref)))
    tmp = build / 'model.glm'
    keys = {}
    same = differ = 0
    opened = {}
    t_all = time.time()
    for i, (qpath, (pack, member)) in enumerate(sorted(glms.items())):
        if a.limit and i >= a.limit:
            break
        z = opened.setdefault(pack, zipfile.ZipFile(pack))
        data = z.read(member)
        tmp.write_bytes(data)
        t0 = time.time()
        r = subprocess.run([str(exe), str(tmp), str(tandir)], capture_output=True, text=True)
        ms = (time.time() - t0) * 1000
        if r.returncode:
            print('%-58s skipped (%s)' % (qpath, r.stdout.strip() or r.returncode))
            continue
        key, size, nl, verts = r.stdout.split()
        keys.setdefault(key, []).append(qpath)
        note = ''
        if ref:
            out = (tandir / (key + '.xtan')).read_bytes()
            nl_ = struct.unpack_from('<I', out, 20)[0]
            counts = struct.unpack_from('<%dI' % nl_, out, 24)
            got = ref.get((int(size), counts))
            if got:
                ok = got[0] == out[24 + 4 * nl_:]
                same += ok
                differ += not ok
                note = '  game file v%d %s' % (got[2], 'EQUAL' if ok else 'DIFFERENT')
        print('%-58s %s %5d verts %6.0f ms%s' % (qpath, key, int(verts), ms, note))
    print('cooked %d GLMs into %d files in %.0f s; compared with the game: %d equal, %d different' % (
        sum(len(v) for v in keys.values()), len(keys), time.time() - t_all, same, differ))
    if a.pack:
        assert not a.pack.exists(), 'never rebuild a pk3 in place: bump the name'
        with zipfile.ZipFile(a.pack, 'w', zipfile.ZIP_STORED) as zp:
            for key in sorted(keys):
                zp.write(tandir / (key + '.xtan'), 'cache/tangents/%s.xtan' % key)
        print('wrote', a.pack, a.pack.stat().st_size)
    sys.exit(1 if differ else 0)


if __name__ == '__main__':
    main()
