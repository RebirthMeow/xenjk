"""Compile rd-vulkan's garment-cloth compute shaders into shaders/spirv/cloth_shader_data.c (no Vulkan SDK).

    python tools/cloth_spirv.py [--tree <rd-vulkan dir>]
    python tools/cloth_spirv.py --check     # exit 1 when the GLSL changed since the arrays were built
    python tools/cloth_spirv.py --stamp     # record the current sources' hash without compiling (only after a build
                                            # made some other way from exactly these sources, e.g. Khronos glslang)

Compiles shaders/glsl/cloth_step.comp and cloth_draw.comp with Godot's glslang (the path of renderer_spirv.py:
#include inlined, SPIR-V 1.3 turned into 1.0) and writes the C arrays cloth_step_comp_spv / cloth_draw_comp_spv.
The engine's own shader_data.c is not touched.
"""
import argparse
import json
import os
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import renderer_spirv as rs  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
SHADERS = ('cloth_step', 'cloth_draw')
SOURCES = ('cloth_layout.h', 'cloth_step.comp', 'cloth_draw.comp')
STAMP = '// sources sha256: '


def sources_hash(glsl):
    """One sha256 over the GLSL the arrays are built from (line endings normalised, so a checkout's CRLF does not
    count as a change)."""
    import hashlib
    h = hashlib.sha256()
    for name in SOURCES:
        h.update(name.encode('ascii') + b'\0')
        h.update((glsl / name).read_bytes().replace(b'\r\n', b'\n'))
    return h.hexdigest()


def stamped(out):
    for line in out.read_text(encoding='utf-8').splitlines()[:8]:
        if line.startswith(STAMP):
            return line[len(STAMP):].strip()
    return None


def stamp(out, digest):
    text = out.read_text(encoding='utf-8')
    lines = [l for l in text.splitlines() if not l.startswith(STAMP)]
    lines.insert(1, STAMP + digest)
    out.write_text('\n'.join(lines) + '\n', encoding='utf-8', newline='\r\n')


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument('--tree', default=str(ROOT / 'codemp' / 'rd-vulkan'))
    ap.add_argument('--check', action='store_true')
    ap.add_argument('--stamp', action='store_true')
    a = ap.parse_args(argv)
    tree = Path(a.tree)
    glsl = tree / 'shaders' / 'glsl'
    data_c = tree / 'shaders' / 'spirv' / 'cloth_shader_data.c'
    if a.check or a.stamp:
        digest = sources_hash(glsl)
        if a.stamp:
            stamp(data_c, digest)
            print('stamped', data_c, digest)
            return
        have = stamped(data_c)
        if have != digest:
            print('cloth SPIR-V is stale: sources %s, arrays built from %s; run tools/cloth_spirv.py' % (digest, have))
            raise SystemExit(1)
        print('cloth SPIR-V matches its sources', digest)
        return
    work = rs.WORK.parent / 'cloth-spirv-work'
    src_dir, spv_dir = work / 'src', work / 'spv'
    src_dir.mkdir(parents=True, exist_ok=True)
    spv_dir.mkdir(parents=True, exist_ok=True)
    jobs = []
    for name in SHADERS:
        src = src_dir / (name + '.comp')
        src.write_text(rs.preprocess(glsl, name + '.comp', ''), encoding='utf-8', newline='\n')
        out = spv_dir / (name + '.spv')
        if out.exists():
            out.unlink()   # regenerated output of this tool
        jobs.append({'name': name, 'stage': 'comp', 'src': str(src), 'out': str(out)})
    (work / 'jobs.json').write_text(json.dumps(jobs), encoding='utf-8')
    (work / 'project.godot').write_text('config_version=5\n[application]\nconfig/name="spirv"\n', encoding='utf-8')
    (work / 'compile.gd').write_text(rs.GD_SCRIPT, encoding='utf-8', newline='\n')
    if not rs.GODOT.exists():
        raise SystemExit('Godot not found at %s (set GODOT_EXE)' % rs.GODOT)
    env = dict(os.environ, GDC_JOBS=str(work / 'jobs.json'))
    r = subprocess.run([str(rs.GODOT), '--rendering-driver', 'vulkan', '--windowed', '--resolution', '64x64',
                        '--position', '-4000,-4000', '--audio-driver', 'Dummy', '--path', str(work), '--script',
                        'compile.gd'], env=env, capture_output=True, text=True, timeout=600)
    text = r.stdout + r.stderr
    if r.returncode != 0 or 'FAILED' in text:
        print(text)
        raise SystemExit('godot exited %d' % r.returncode)
    parts = ['// Generated by tools/cloth_spirv.py from shaders/glsl/cloth_*.comp: do not edit.\n']
    for name in SHADERS:
        data = rs.to_spirv10((spv_dir / (name + '.spv')).read_bytes())
        parts.append(rs.c_array(name + '_comp_spv', data))
        parts.append('const unsigned int %s_comp_spv_size = sizeof(%s_comp_spv);\n' % (name, name))
    out = tree / 'shaders' / 'spirv' / 'cloth_shader_data.c'
    out.write_text('\n'.join(parts), encoding='utf-8', newline='\r\n')
    stamp(out, sources_hash(glsl))   # --check compares the GLSL against this
    print('wrote', out)


if __name__ == '__main__':
    main()
