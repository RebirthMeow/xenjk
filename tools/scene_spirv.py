"""Compile rd-vulkan's render-scene shaders into shaders/spirv/scene_shader_data.c.

    python tools/scene_spirv.py [--tree <rd-vulkan dir>]

Compiles shaders/glsl/scene/*.vert, *.frag and *.comp (the SHADERS list) with Khronos' glslang (the compiler
renderer_spirv.py uses; `-V` writes SPIR-V 1.0; the GPU-driven variants, compiled with defines, target Vulkan 1.2)
and writes one C array per shader, named for its file (scene_vert_spv,
scene_ssr_comp_spv, ...), for vk_scene.cpp. The engine's own shader_data.c is not touched.
"""
import argparse
import subprocess
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import renderer_spirv as rs  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
# (file, stage, array, defines, target): target None is glslang's default (Vulkan 1.0, SPIR-V 1.0)
SHADERS = (('scene.vert', 'vert', 'scene_vert_spv', (), None), ('scene.frag', 'frag', 'scene_frag_spv', (), None),
           ('scene_cull.comp', 'comp', 'scene_cull_comp_spv', (), None), ('scene_occ.comp', 'comp', 'scene_occ_ms_comp_spv', ('-DDEPTH_MS',), 'vulkan1.2'), ('scene_occ.comp', 'comp', 'scene_occ_1_comp_spv', (), 'vulkan1.2'),
           ('scene_fog.comp', 'comp', 'scene_fog_comp_spv', (), None),
           ('scene_sky.vert', 'vert', 'scene_sky_vert_spv', (), None), ('scene_fx.vert', 'vert', 'scene_fx_vert_spv', (), None), ('scene_capture.comp', 'comp', 'scene_capture_comp_spv', (), None), ('scene_meter.comp', 'comp', 'scene_meter_comp_spv', (), None),
           ('scene_ssr.comp', 'comp', 'scene_ssr_comp_spv', (), None), ('scene_capture.comp', 'comp', 'scene_capture_nocopy_comp_spv', ('-DNO_DEPTH_COPY',), 'vulkan1.0'), ('scene_grade.vert', 'vert', 'scene_grade_vert_spv', (), None),
           ('scene_grade.frag', 'frag', 'scene_grade_frag_spv', (), None), ('scene_grade.frag', 'comp', 'scene_grade_comp_spv', ('-DGRADE_COMPUTE',), 'vulkan1.2'), ('scene_compact.comp', 'comp', 'scene_compact_comp_spv', (), 'vulkan1.2'),
           # GPU-driven draws (r_sceneGpuDriven): Vulkan 1.2 (draw parameters, descriptor indexing)
           ('scene.vert', 'vert', 'scene_vert_gd_spv', ('-DGPU_DRIVEN',), 'vulkan1.2'),
           ('scene.vert', 'vert', 'scene_vert_gd_vrs_spv', ('-DGPU_DRIVEN', '-DVRS'), 'vulkan1.2'),	# r_sceneVrs (VK_KHR_fragment_shading_rate)
           ('scene.frag', 'frag', 'scene_frag_gd_spv', ('-DGPU_DRIVEN',), 'vulkan1.2'),
           ('scene.frag', 'frag', 'scene_frag_gd_mask_spv', ('-DGPU_DRIVEN', '-DFADE_SAMPLEMASK'), 'vulkan1.2'),	# r_sceneHideDither 2
           ('scene.frag', 'frag', 'scene_frag_gdlit_spv', ('-DGPU_DRIVEN', '-DGPU_DRIVEN_LIT'), 'vulkan1.2'),
           ('scene.frag', 'frag', 'scene_frag_gdlit_nodebug_spv', ('-DGPU_DRIVEN', '-DGPU_DRIVEN_LIT', '-DNO_DEBUG_VIEWS'), 'vulkan1.2'),
           ('scene.frag', 'frag', 'scene_frag_gdlit_cov_spv', ('-DGPU_DRIVEN', '-DGPU_DRIVEN_LIT', '-DNO_DEBUG_VIEWS', '-DCUTOUT_COVERAGE'), 'vulkan1.2'),	# r_sceneCutoutCoverage
           # mesh decals (r_sceneDecals): the decal pass, reading the depth attachment (its MSAA samples' first)
           ('scene.frag', 'frag', 'scene_frag_decal_spv', ('-DDECAL',), 'vulkan1.0'),
           ('scene.frag', 'frag', 'scene_frag_decal_ms_spv', ('-DDECAL', '-DDEPTH_MS'), 'vulkan1.0'),
           # projected decals (r_scenePDecals, maps/<map>.xdcl): boxes into the same pass
           ('scene_pdecal.vert', 'vert', 'scene_pdecal_vert_spv', (), 'vulkan1.0'),
           ('scene_pdecal.frag', 'frag', 'scene_pdecal_frag_spv', (), 'vulkan1.0'),
           ('scene_pdecal.frag', 'frag', 'scene_pdecal_frag_ms_spv', ('-DDEPTH_MS',), 'vulkan1.0'),
           ('scene_cluster.comp', 'comp', 'scene_cluster_comp_spv', (), 'vulkan1.2'),
           ('scene_sort.comp', 'comp', 'scene_sort_comp_spv', (), 'vulkan1.2'),
           ('scene_lightfade.comp', 'comp', 'scene_lightfade_comp_spv', (), 'vulkan1.2'),
           ('scene_water.comp', 'comp', 'scene_water_comp_spv', (), 'vulkan1.2'),
           ('scene_scatter.comp', 'comp', 'scene_scatter_comp_spv', (), 'vulkan1.2'),
           ('scene_groupcull.comp', 'comp', 'scene_groupcull_comp_spv', (), 'vulkan1.2'),
           ('scene_rotate.comp', 'comp', 'scene_rotate_comp_spv', (), 'vulkan1.2'),
           ('scene_distant.comp', 'comp', 'scene_distant_comp_spv', (), 'vulkan1.2'),
           ('scene_viewcull.comp', 'comp', 'scene_viewcull_comp_spv', (), 'vulkan1.2'),
           ('scene_want.comp', 'comp', 'scene_want_comp_spv', (), 'vulkan1.2'))


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument('--tree', default=str(ROOT / 'codemp' / 'rd-vulkan'))
    a = ap.parse_args(argv)
    tree = Path(a.tree)
    src = tree / 'shaders' / 'glsl' / 'scene'
    if not rs.GLSLANG.exists():
        raise SystemExit('glslang not found at %s (set GLSLANG_EXE)' % rs.GLSLANG)
    parts = ['// Generated by tools/scene_spirv.py from shaders/glsl/scene/: do not edit.\n']
    with tempfile.TemporaryDirectory() as tmp:
        for name, stage, var, defines, target in SHADERS:
            out = Path(tmp) / (var + '.spv')
            extra = (['--target-env', target] if target else []) + list(defines)
            r = subprocess.run([str(rs.GLSLANG), '-S', stage, '-V'] + extra + ['-o', str(out), str(src / name)],
                               capture_output=True, text=True)
            if r.returncode != 0:
                print(r.stdout + r.stderr)
                raise SystemExit('%s: glslang exited %d' % (name, r.returncode))
            data = out.read_bytes()
            parts.append(rs.c_array(var, data))
            parts.append('const unsigned int %s_size = sizeof(%s);\n' % (var, var))
    dst = tree / 'shaders' / 'spirv' / 'scene_shader_data.c'
    dst.write_text('\n'.join(parts), encoding='utf-8', newline='\r\n')
    print('wrote', dst)


if __name__ == '__main__':
    main()
