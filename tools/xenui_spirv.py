"""Compile rd-vulkan's xenui shaders into shaders/spirv/xenui_shader_data.c (tr_xenui.cpp).

    python -I tools/xenui_spirv.py [--tree <rd-vulkan dir>]

Compiles shaders/glsl/xenui_*.vert and xenui_*.frag with Khronos glslang (tools/renderer_spirv.py's GLSLANG:
env GLSLANG_EXE, or glslang on PATH) and writes one C array per shader, <name>_<stage>_spv, with its size. The engine's own
shader_data.c is not touched (renderer_spirv.py skips xenui_* files).
"""
import argparse
import subprocess
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import renderer_spirv as rs  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument('--tree', default=str(ROOT / 'codemp' / 'rd-vulkan'))
    a = ap.parse_args(argv)
    tree = Path(a.tree)
    glsl = tree / 'shaders' / 'glsl'
    if not rs.GLSLANG.exists():
        raise SystemExit('glslang not found at %s (set GLSLANG_EXE)' % rs.GLSLANG)
    parts = ['// Generated by tools/xenui_spirv.py from shaders/glsl/xenui_*: do not edit.\n']
    with tempfile.TemporaryDirectory() as tmp:
        for src in sorted(glsl.glob('xenui_*.vert')) + sorted(glsl.glob('xenui_*.frag')):
            stage = src.suffix[1:]
            var = '%s_%s_spv' % (src.stem, stage)
            out = Path(tmp) / (var + '.spv')
            r = subprocess.run([str(rs.GLSLANG), '-S', stage, '-V', '-o', str(out), src.name], cwd=str(glsl),
                               capture_output=True, text=True, timeout=120)
            if r.returncode != 0 or not out.exists():
                raise SystemExit('%s failed:\n%s' % (src.name, (r.stdout + r.stderr).strip()))
            parts.append(rs.c_array(var, out.read_bytes()))
            parts.append('const unsigned int %s_size = sizeof(%s);\n' % (var, var))
    dest = tree / 'shaders' / 'spirv' / 'xenui_shader_data.c'
    dest.write_text('\n'.join(parts), encoding='utf-8', newline='\r\n')
    print('wrote', dest)


if __name__ == '__main__':
    main()
